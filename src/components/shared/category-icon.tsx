export const iconForKey = (key: string | undefined): LucideIcon =>
  (key && CATEGORY_ICONS[key]) || CircleDot;

export function CategoryIcon({ categoryId, className }: { categoryId: string; className?: string }) {
  const categories = useCategories();
  // createElement, not JSX: the icon is looked up at render time and is not a component defined here.
  return createElement(iconForKey(categories.find((c) => c.id === categoryId)?.icon), {
    "aria-hidden": true,
    className: cn("size-4 shrink-0", className),
  });
}
